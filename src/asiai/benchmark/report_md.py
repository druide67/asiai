"""Markdown report renderer — one generic renderer for every bench type.

The variability lives in :mod:`asiai.benchmark.result_model`; this module
is pure layout. The structure is fixed so a report is complete and
unbiased by construction:

1. Title + type + date
2. Headline (with its explicit label — never a naked number)
3. Subjects × metrics table (value ± CI95, n, caveats as footnotes)
4. Conditions (quant, context, extra_body, powermode, ...)
5. Quality gates (including a refused ranking)
6. Provenance (versions, hardware, dataset)
"""

from __future__ import annotations

import time

from asiai.benchmark.result_model import BenchResult, MetricValue

_DIRECTION_HINT = {"higher": "↑ better", "lower": "↓ better"}


def _fmt_value(m: MetricValue) -> str:
    if m.value is None:
        return "—"
    if isinstance(m.value, float):
        text = f"{m.value:,.2f}".rstrip("0").rstrip(".")
    else:
        text = str(m.value)
    if m.unit:
        text += f" {m.unit}"
    if m.ci95:
        text += f" (CI95 {m.ci95[0]:g}–{m.ci95[1]:g})"
    if m.n == 1:
        text += " · n=1 — no noise estimate"
    elif m.n > 1:
        text += f" · n={m.n}"
    return text


def render_markdown(result: BenchResult) -> str:
    lines: list[str] = []
    add = lines.append

    add(f"# {result.title}")
    add("")
    ts = result.provenance.get("started_at", "")
    date = ""
    if ts.isdigit():
        date = time.strftime("%Y-%m-%d %H:%M", time.localtime(int(ts)))
    add(f"*Bench type: `{result.bench_type}`*" + (f" · *{date}*" if date else ""))
    add("")

    if result.headline is not None:
        add(f"**Headline — `{result.headline.label}`: {_fmt_value(result.headline)}**")
        add("")
    if result.winner:
        add(f"**Winner: {result.winner}**")
        add("")
    elif result.winner_note:
        add(f"**No winner declared** — {result.winner_note}")
        add("")

    # ── Results ──────────────────────────────────────────────────────
    footnotes: list[str] = []

    def _with_footnote(m: MetricValue, text: str) -> str:
        if m.caveat:
            footnotes.append(f"[^{len(footnotes) + 1}]: {m.label}: {m.caveat}")
            return f"{text}[^{len(footnotes)}]"
        return text

    add("## Results")
    add("")
    for subject in result.subjects:
        add(f"### {subject.label}")
        add("")
        add("| Metric | Value |")
        add("|---|---|")
        rows = ([subject.hero] if subject.hero else []) + [
            m for m in subject.metrics if m is not subject.hero
        ]
        for m in rows:
            hint = _DIRECTION_HINT.get(m.direction, "")
            label = f"{m.label}" + (f" ({hint})" if hint else "")
            add(f"| {label} | {_with_footnote(m, _fmt_value(m))} |")
        add("")

    # ── Conditions ───────────────────────────────────────────────────
    add("## Conditions")
    add("")
    if result.conditions:
        add("| Condition | Value |")
        add("|---|---|")
        for key in sorted(result.conditions):
            add(f"| {key} | {result.conditions[key]} |")
    else:
        add("*No condition metadata recorded — treat comparisons with caution.*")
    add("")

    # ── Quality gates ────────────────────────────────────────────────
    if result.gates:
        add("## Quality gates")
        add("")
        for gate in result.gates:
            mark = "✅" if gate.passed else "❌"
            detail = f" — {gate.detail}" if gate.detail else ""
            add(f"- {mark} `{gate.name}`{detail}")
        add("")

    # ── Provenance ───────────────────────────────────────────────────
    add("## Provenance")
    add("")
    add("| Field | Value |")
    add("|---|---|")
    for key in sorted(result.provenance):
        if key == "started_at":
            continue  # already rendered as the date
        add(f"| {key} | {result.provenance[key]} |")
    add("")

    if footnotes:
        lines.extend(footnotes)
        lines.append("")

    add(
        "*Generated by [asiai](https://asiai.dev) — numbers carry their "
        "uncertainty and conditions; a result without them is not comparable.*"
    )
    add("")
    return "\n".join(lines)
